-- PostgreSQL 15+. Initial migration: run once in a fresh database.
-- All dates use [effective_from, effective_to]; NULL end means unbounded.
BEGIN;
CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE documents (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_number text NOT NULL UNIQUE CHECK (btrim(document_number) <> ''),
    title text NOT NULL CHECK (btrim(title) <> ''),
    issuing_body text NOT NULL CHECK (btrim(issuing_body) <> ''),
    issued_on date NOT NULL CHECK (isfinite(issued_on)),
    source_url text NOT NULL CHECK (source_url ~ '^https?://[^[:space:]]+$'),
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE ingestion_snapshots (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id bigint NOT NULL REFERENCES documents(id),
    source_url text NOT NULL CHECK (source_url ~ '^https?://[^[:space:]]+$'),
    fetched_at timestamptz NOT NULL DEFAULT now(),
    content_sha256 text NOT NULL CHECK (content_sha256 ~ '^[0-9a-f]{64}$'),
    raw_payload jsonb NOT NULL,
    UNIQUE (id, document_id)
);

CREATE TABLE document_versions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id bigint NOT NULL REFERENCES documents(id),
    version_number integer NOT NULL CHECK (version_number > 0),
    title text NOT NULL CHECK (btrim(title) <> ''),
    source_url text NOT NULL CHECK (source_url ~ '^https?://[^[:space:]]+$'),
    ingestion_snapshot_id bigint NOT NULL,
    status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'approved', 'rejected')),
    approved_at timestamptz,
    approved_by text,
    effective_from date NOT NULL CHECK (isfinite(effective_from)),
    effective_to date CHECK (isfinite(effective_to)),
    effective_interval daterange GENERATED ALWAYS AS
        (daterange(effective_from, effective_to, '[]')) STORED,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (document_id, version_number),
    FOREIGN KEY (ingestion_snapshot_id, document_id)
        REFERENCES ingestion_snapshots(id, document_id),
    CHECK (effective_to IS NULL OR effective_to > effective_from),
    CHECK (status <> 'approved' OR
        (approved_at IS NOT NULL AND approved_by IS NOT NULL AND btrim(approved_by) <> '')),
    -- Also protects concurrent approvals; do not replace with SELECT-before-INSERT.
    CONSTRAINT approved_versions_do_not_overlap EXCLUDE USING gist (
        document_id WITH =, effective_interval WITH &&
    ) WHERE (status = 'approved')
);

-- A version is a COMPLETE snapshot, including unchanged articles.
-- Provisions inherit their version's effective interval and approval atomically.
-- Do not independently approve articles or fall back to another version.
CREATE TABLE provisions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_version_id bigint NOT NULL REFERENCES document_versions(id),
    article_key text NOT NULL CHECK (btrim(article_key) <> ''),
    heading text NOT NULL CHECK (btrim(heading) <> ''),
    body text NOT NULL CHECK (btrim(body) <> ''),
    source_url text NOT NULL CHECK (source_url ~ '^https?://[^[:space:]]+$'),
    search_vector tsvector GENERATED ALWAYS AS (
        setweight(to_tsvector('simple'::regconfig, heading), 'A') ||
        setweight(to_tsvector('simple'::regconfig, body), 'B')
    ) STORED,
    UNIQUE (document_version_id, article_key)
);
CREATE INDEX provisions_search_idx ON provisions USING gin (search_vector);

-- Provenance metadata only: these edges never merge content in lookup queries.
CREATE TABLE document_relations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_document_id bigint NOT NULL REFERENCES documents(id),
    to_document_id bigint NOT NULL REFERENCES documents(id),
    relation_type text NOT NULL CHECK (relation_type IN ('amends', 'repeals', 'guides', 'consolidates')),
    source_url text NOT NULL CHECK (source_url ~ '^https?://[^[:space:]]+$'),
    effective_from date NOT NULL CHECK (isfinite(effective_from)),
    effective_to date CHECK (isfinite(effective_to)),
    CHECK (from_document_id <> to_document_id),
    CHECK (effective_to IS NULL OR effective_to > effective_from),
    UNIQUE (from_document_id, to_document_id, relation_type, effective_from)
);
CREATE INDEX document_relations_to_idx ON document_relations(to_document_id);
CREATE INDEX ingestion_snapshots_document_idx ON ingestion_snapshots(document_id);
COMMIT;
